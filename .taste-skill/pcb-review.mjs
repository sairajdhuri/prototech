import { chromium } from 'playwright';
import fs from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.on('pageerror',e=>console.log('PAGEERROR:',e.message));
page.on('console',m=>{if(m.type()==='warning'||m.type()==='error')console.log(m.type(),m.text().slice(0,250));});
await page.goto('http://localhost:3000',{waitUntil:'networkidle'});
await page.locator('.webgl-ready').waitFor({timeout:60000});
await fs.mkdir('.taste-skill/pcb',{recursive:true});
await page.screenshot({path:'.taste-skill/pcb/desktop-hero.png'});
await page.locator('.pcb-chapter').scrollIntoViewIfNeeded();
await page.waitForTimeout(1200);
await page.screenshot({path:'.taste-skill/pcb/desktop-layers.png'});
await page.setViewportSize({width:390,height:844});
await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
await page.waitForTimeout(1200);
await page.screenshot({path:'.taste-skill/pcb/mobile-hero.png'});
await page.locator('.pcb-chapter').scrollIntoViewIfNeeded();
await page.waitForTimeout(1200);
await page.screenshot({path:'.taste-skill/pcb/mobile-layers.png'});
console.log('Overflow:',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
await browser.close();
